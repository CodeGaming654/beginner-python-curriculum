print(4 + 5)  # Addition: adds two numbers

print(10 - 5)  # Subtraction: subtracts the second number from the first number

print(6 * 7)  # Multiplication: multiplies two numbers

print(15 / 2)  # Division: divides and gives a float result

print(15 // 2)  # Floor division: divides and rounds down to whole number

print(15 % 2)  # Modulus: gives the remainder

print (2 ** 3) # Exponentiation: first number raised to the power of second number

# You can combine numbers and math operators
# Python follows the order of operations
print(2 + 3 * 4)  # prints 14 (3 * 4 = 12, then 2 + 12)
print((2 + 3) * 4)  # print 20 (2 + 3 = 5, then 5 * 4)

